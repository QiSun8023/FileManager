import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../module/webroot/theme.js',import.meta.url),'utf8');
const {normalizePreferences,resolveMonetPalette,paletteTone,accents}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
assert.equal(accents.length,6);
assert.deepEqual(normalizePreferences(null),{accent:'green',scheme:'system',monet:false});
assert.deepEqual(normalizePreferences({accent:'blue',scheme:'dark',monet:true}),{accent:'blue',scheme:'dark',monet:true});
assert.deepEqual(normalizePreferences({accent:'invalid',scheme:'invalid',monet:'true'}),{accent:'green',scheme:'system',monet:false});
console.log('PASS appearance settings retain valid choices and reject malformed data');
assert.equal(resolveMonetPalette({}),null);
assert.equal(resolveMonetPalette({primary:'#286548',onPrimary:'#ffffff',surface:'#fff',onSurface:'bad'}),null);
console.log('PASS absent/invalid host colors cannot be advertised as active Monet');
const colors={primary:'#abc9ff',onPrimary:'#14251d',surface:'#152015ff',onSurface:'#eeeeee',background:'#111111',primaryContainer:'#334455',onPrimaryContainer:'#ffffff',outlineVariant:'#445566'};
const palette=resolveMonetPalette(colors);
assert.equal(palette['--accent'],'#abc9ff');assert.equal(palette['--card'],'#152015ff');assert.equal(palette['--page'],'#111111');
console.log('PASS complete host palette maps to accent, surfaces, text and selection colors');
assert.equal(paletteTone('#152015ff'),'dark');assert.equal(paletteTone('rgb(250, 250, 250)'),'light');assert.equal(paletteTone('bad'),null);
console.log('PASS host palette controls appropriate light/dark native form rendering');
console.log('Theme: 4 scenarios passed.');
